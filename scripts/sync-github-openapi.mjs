import { execFile } from 'node:child_process'
import { writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { promisify } from 'node:util'

const execFileAsync = promisify(execFile)

const source =
  'https://raw.githubusercontent.com/github/rest-api-description/main/descriptions/api.github.com/api.github.com.json'
const permissionsSource =
  'https://raw.githubusercontent.com/github/docs/main/src/github-apps/data/fpt-2026-03-10/server-to-server-permissions.json'
const operationsSource =
  'https://raw.githubusercontent.com/github/docs/main/src/github-apps/data/fpt-2026-03-10/server-to-server-rest.json'
const [document, permissions, operations] = await Promise.all([
  fetchJson(source),
  fetchJson(permissionsSource),
  fetchJson(operationsSource),
])
if (!document.paths || typeof document.paths !== 'object') throw new Error('GitHub OpenAPI paths are missing.')

const installationOperations = Object.fromEntries(
  Object.values(operations)
    .flat()
    .map(({ verb, requestPath }) => [`${verb.toLowerCase()} ${requestPath}`, true])
    .sort(([left], [right]) => left.localeCompare(right)),
)
const operationScopes = {}
for (const [permission, definition] of Object.entries(permissions)) {
  for (const operation of definition.permissions) {
    const key = `${operation.verb.toLowerCase()} ${operation.requestPath}`
    const scope = `${permission}:${operation.access}`
    operationScopes[key] ??= []
    if (!operationScopes[key].includes(scope)) operationScopes[key].push(scope)
  }
}
for (const scopes of Object.values(operationScopes)) scopes.sort()
const sortedScopes = Object.fromEntries(
  Object.entries(operationScopes).sort(([left], [right]) => left.localeCompare(right)),
)
const output = `// Generated by scripts/sync-github-openapi.mjs. Do not edit by hand.\nexport const githubOpenApiSource = ${JSON.stringify(source)}\nexport const githubPermissionSource = ${JSON.stringify(permissionsSource)}\nexport const githubInstallationOperationSource = ${JSON.stringify(operationsSource)}\nexport const githubInstallationOperations = ${JSON.stringify(installationOperations, null, 2)} as const\nexport const githubOperationScopes = ${JSON.stringify(sortedScopes, null, 2)} as const\n`
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const outputPath = resolve(root, 'src/providers/github/openapi-paths.ts')
await writeFile(outputPath, output)
await execFileAsync(resolve(root, 'node_modules/.bin/biome'), ['format', '--write', outputPath])

async function fetchJson(url) {
  const response = await fetch(url)
  if (!response.ok) throw new Error(`${url} download failed with ${response.status}.`)
  return response.json()
}
