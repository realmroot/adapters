import { execFile } from 'node:child_process'
import { writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { promisify } from 'node:util'

const execFileAsync = promisify(execFile)

const source =
  'https://raw.githubusercontent.com/github/rest-api-description/main/descriptions/api.github.com/api.github.com.json'
const permissionDataSource = 'https://api.github.com/repos/github/docs/contents/src/rest/data/fpt-2026-03-10'
const permissionNameSource =
  'https://raw.githubusercontent.com/github/docs/main/src/github-apps/data/fpt-2026-03-10/server-to-server-permissions.json'
const [document, permissionFiles, permissionNames] = await Promise.all([
  fetchJson(source),
  fetchJson(permissionDataSource),
  fetchJson(permissionNameSource),
])
if (!document.paths || typeof document.paths !== 'object') throw new Error('GitHub OpenAPI paths are missing.')
if (!Array.isArray(permissionFiles)) throw new Error('GitHub structured REST data directory is missing.')

const structuredDocuments = await Promise.all(
  permissionFiles
    .filter((file) => file.name?.endsWith('.json') && file.download_url)
    .map((file) => fetchJson(file.download_url)),
)
const permissionSlugs = new Map(
  Object.entries(permissionNames).map(([slug, definition]) => [definition.displayTitle, slug]),
)
permissionSlugs.set('Enterprise permissions for "Enterprise administration"', 'enterprise_administration')

const operationRequirements = {}
for (const structuredDocument of structuredDocuments) collectOperations(structuredDocument)
for (const [permission, definition] of Object.entries(permissionNames)) {
  for (const operation of definition.permissions) {
    const key = `${operation.verb.toLowerCase()} ${operation.requestPath}`
    if (!operationRequirements[key] && operation['server-to-server']) {
      operationRequirements[key] = [[`${permission}:${permissionAccess(operation.access)}`]]
    }
  }
}
// GitHub's uploads-origin operation has no progAccess block, although release asset upload uses Contents write.
operationRequirements['post /repos/{owner}/{repo}/releases/{release_id}/assets'] ??= [['contents:write']]
for (const [key, requirements] of Object.entries(operationRequirements)) {
  operationRequirements[key] = uniqueRequirements(requirements).sort(compareRequirements)
}
const sortedRequirements = Object.fromEntries(
  Object.entries(operationRequirements).sort(([left], [right]) => left.localeCompare(right)),
)
const installationOperations = Object.fromEntries(Object.keys(sortedRequirements).map((key) => [key, true]))
const output = `// Generated by scripts/sync-github-openapi.mjs. Do not edit by hand.\nexport const githubOpenApiSource = ${JSON.stringify(source)}\nexport const githubPermissionSource = ${JSON.stringify(permissionDataSource)}\nexport const githubPermissionNameSource = ${JSON.stringify(permissionNameSource)}\nexport const githubInstallationOperationSource = ${JSON.stringify(permissionDataSource)}\nexport const githubInstallationOperations = ${JSON.stringify(installationOperations, null, 2)} as const\nexport const githubOperationRequirements = ${JSON.stringify(sortedRequirements, null, 2)} as const\n`
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const outputPath = resolve(root, 'src/providers/github/openapi-paths.ts')
await writeFile(outputPath, output)
await execFileAsync(resolve(root, 'node_modules/.bin/biome'), ['format', '--write', outputPath])

function collectOperations(value) {
  if (!value || typeof value !== 'object') return
  if (typeof value.verb === 'string' && typeof value.requestPath === 'string' && value.progAccess?.serverToServer) {
    const key = `${value.verb.toLowerCase()} ${value.requestPath}`
    operationRequirements[key] ??= []
    for (const permissionAlternative of value.progAccess.permissions ?? []) {
      operationRequirements[key].push(
        Object.entries(permissionAlternative)
          .map(([label, access]) => `${permissionSlug(label)}:${permissionAccess(access)}`)
          .sort(),
      )
    }
    if (value.progAccess.allowsPublicRead || value.progAccess.allowPermissionlessAccess) {
      operationRequirements[key].push(['metadata:read'])
    }
    if (operationRequirements[key].length === 0) operationRequirements[key].push(['metadata:read'])
  }
  for (const child of Object.values(value)) collectOperations(child)
}

function permissionSlug(label) {
  const match = /^"(.+)" (repository|organization|enterprise|user) permissions$/.exec(label)
  if (!match) throw new Error(`Unknown GitHub permission label: ${label}`)
  const displayTitle = `${capitalize(match[2])} permissions for "${match[1]}"`
  const slug = permissionSlugs.get(displayTitle)
  if (!slug) throw new Error(`GitHub permission slug is missing for ${label}.`)
  return slug
}

function permissionAccess(access) {
  if (access !== 'read' && access !== 'write' && access !== 'admin') {
    throw new Error(`Unknown GitHub permission access: ${access}`)
  }
  return access
}

function uniqueRequirements(requirements) {
  return [...new Map(requirements.map((requirement) => [requirement.join('\0'), requirement])).values()]
}

function compareRequirements(left, right) {
  return left.length - right.length || left.join('\0').localeCompare(right.join('\0'))
}

function capitalize(value) {
  return value[0].toUpperCase() + value.slice(1)
}

async function fetchJson(url) {
  const response = await fetch(url, { headers: { 'User-Agent': 'realmroot-adapters-openapi-sync' } })
  if (!response.ok) throw new Error(`${url} download failed with ${response.status}.`)
  return response.json()
}
